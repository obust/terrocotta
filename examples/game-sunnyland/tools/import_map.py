#!/usr/bin/env python3
"""Generate the checked-in Roc level constants from the Phaser Tiled map."""
import json
from pathlib import Path

ROOT = Path(__file__).parents[1]
source = ROOT / "assets/maps/map.json"
target = ROOT / "world/LevelData.roc"
data = json.loads(source.read_text())
assert (data["width"], data["height"], data["tilewidth"], data["tileheight"]) == (58, 25, 16, 16)
tiles = data["layers"][0]["data"]
assert len(tiles) == 58 * 25

# Tiled stores horizontal/vertical/diagonal flips in the high three bits.
gid_mask = 0x1FFFFFFF
normalized = [gid & gid_mask for gid in tiles]
flags = [gid & ~gid_mask for gid in tiles]

solid_ids = {27, 29, 31, 33, 35, 37, 77, 81, 86, 87, 127, 129, 131, 133,
             134, 135, 83, 84, 502, 504, 505, 529, 530, 333, 335, 337,
             339, 366, 368, 262, 191, 193, 195, 241, 245, 291, 293, 295}
# These are the exact top-only collision IDs from the Phaser reference.
one_way_ids = {35, 36, 84, 86, 134, 135, 366, 367, 368, 262}

def runs(ids):
    result = []
    for y in range(data["height"]):
        x = 0
        while x < data["width"]:
            if normalized[y * data["width"] + x] not in ids:
                x += 1
                continue
            start = x
            while x < data["width"] and normalized[y * data["width"] + x] in ids:
                x += 1
            result.append((start * 16, y * 16, (x - start) * 16, 16))
    return result

def roc_list(values):
    return "[" + ", ".join(str(v) for v in values) + "]"


def roc_rows(values):
    return "[\n" + ",\n".join(
        "\t" + roc_list(values[y * data["width"]:(y + 1) * data["width"]])
        for y in range(data["height"])
    ) + "\n]"


def roc_tile_rows():
    return "[\n" + ",\n".join(
        "\t[" + ", ".join(
            "{ gid: %s, flags: %s }" % (
                normalized[y * data["width"] + x],
                flags[y * data["width"] + x],
            )
            for x in range(data["width"])
        ) + "]"
        for y in range(data["height"])
    ) + "\n]"


def roc_rects(rects):
    return "[\n" + ",\n".join(
        "\t{ x: %s, y: %s, width: %s, height: %s }" % rect
        for rect in rects
    ) + "\n]"


# Phaser first marks solid_ids as fully colliding, then changes the listed
# top-collision IDs to one-way tiles. Mirror that order here.
solid_runs = runs(solid_ids - one_way_ids)
one_way_runs = runs(one_way_ids)

lines = [
    "## Generated by tools/import_map.py; do not hand edit.",
    "LevelData := [].{",
    "width : U64\nwidth = 58\n",
    "height : U64\nheight = 25\n",
    "tile_size : F32\ntile_size = 16\n",
    f"tile_count : U64\ntile_count = {len(normalized)}\n",
    f"flip_count : U64\nflip_count = {sum(1 for flag in flags if flag != 0)}\n",
    f"tile_checksum : U64\ntile_checksum = {sum(normalized) % (2**64)}\n",
    "tile_rows : List(List({ gid : U64, flags : U64 }))\ntile_rows = " + roc_tile_rows() + "\n",
    "solid_count : U64\nsolid_count = " + str(len(solid_runs)) + "\n",
    "solid_runs : List({ x : F32, y : F32, width : F32, height : F32 })\nsolid_runs = " + roc_rects(solid_runs) + "\n",
]
lines += [
    "one_way_count : U64\none_way_count = " + str(len(one_way_runs)) + "\n",
    "one_way_runs : List({ x : F32, y : F32, width : F32, height : F32 })\none_way_runs = " + roc_rects(one_way_runs) + "\n",
]
lines.append("}")
target.write_text("\n".join(lines).rstrip() + "\n")
